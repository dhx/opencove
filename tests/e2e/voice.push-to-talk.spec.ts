import { expect, test, type Page } from '@playwright/test'
import { clearAndSeedWorkspace, launchApp, selectCoveOption } from './workspace-canvas.helpers'
import { isWebE2ETarget } from './webTarget/webTargetLaunch'

// Voice runs on the worker and is offered by the Web UI; the desktop app has no voice engine.
test.skip(!isWebE2ETarget(), 'Voice is a Web UI feature (OPENCOVE_E2E_TARGET=web)')

const VOICE_SAY_LINE = 'You have two agents.'
const TRANSCRIPT = 'list the agents'

async function seedClaudeTask(window: Page): Promise<void> {
  await clearAndSeedWorkspace(
    window,
    [
      {
        id: 'task-voice',
        title: 'Voice boss',
        position: { x: 180, y: 140 },
        width: 460,
        height: 280,
        kind: 'task',
        status: null,
        task: {
          requirement: 'Answer voice prompts',
          status: 'todo',
          priority: 'medium',
          tags: [],
          linkedAgentNodeId: null,
          lastRunAt: null,
          autoGeneratedTitle: false,
          createdAt: '2026-10-25T10:00:00.000Z',
          updatedAt: '2026-10-25T10:00:00.000Z',
        },
      },
    ],
    {
      settings: {
        defaultProvider: 'claude-code',
        customModelEnabledByProvider: { 'claude-code': false },
        customModelByProvider: { 'claude-code': '' },
        customModelOptionsByProvider: { 'claude-code': [] },
      },
    },
  )
}

async function chooseVoiceBoss(window: Page, bossNodeId: string): Promise<void> {
  await window.locator('[data-testid="app-header-settings"]').click({ noWaitAfter: true })
  const dialog = window.getByTestId('settings-panel')
  await expect(dialog).toBeVisible()
  await dialog.getByTestId('settings-section-nav-agent').click()
  await dialog.getByTestId('settings-agent-tab-voice').click()
  await dialog.getByTestId('settings-voice-enabled').click()
  await selectCoveOption(window, 'settings-voice-boss', bossNodeId)
  await window.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
}

async function holdPushToTalk(window: Page, holdMs: number): Promise<void> {
  await window.keyboard.down('Alt')
  await window.keyboard.down('KeyX')
  await window.waitForTimeout(holdMs)
  await window.keyboard.up('KeyX')
  await window.keyboard.up('Alt')
}

/** Records every indicator phase and text, so a failure shows where the turn stopped. */
async function recordVoicePhases(window: Page): Promise<() => Promise<string[]>> {
  await window.evaluate(() => {
    const seen: string[] = []
    ;(window as typeof window & { __voicePhases?: string[] }).__voicePhases = seen
    const record = (): void => {
      const indicator = document.querySelector('[data-testid="voice-indicator"]')
      const entry = indicator
        ? `${indicator.getAttribute('data-voice-phase')}: ${indicator.textContent ?? ''}`
        : 'hidden'
      if (seen.at(-1) !== entry) {
        seen.push(entry)
      }
    }
    new MutationObserver(record).observe(document.body, {
      subtree: true,
      childList: true,
      attributes: true,
      characterData: true,
    })
  })
  return async () =>
    await window.evaluate(
      () => (window as typeof window & { __voicePhases?: string[] }).__voicePhases ?? [],
    )
}

test.describe('Voice - push to talk (Web UI)', () => {
  test('sends the transcript to the boss and speaks its SAY line', async () => {
    const { electronApp, window } = await launchApp({
      windowMode: 'inactive',
      env: {
        OPENCOVE_TEST_VOICE_ENGINE: 'stub',
        OPENCOVE_TEST_VOICE_TRANSCRIPT: TRANSCRIPT,
        OPENCOVE_TEST_AGENT_SESSION_SCENARIO: 'claude-hook-voice-reply',
        OPENCOVE_TEST_CLAUDE_HOOK_INSTALL_FAILURE: '0',
      },
    })
    try {
      await seedClaudeTask(window)
      await window
        .locator('.task-node')
        .first()
        .locator('[data-testid="task-node-run-agent"]')
        .click()
      const agentNode = window.locator('.terminal-node').first()
      await expect(agentNode).toContainText('[opencove-test-voice] ready')
      const bossNodeId = await window
        .locator('.react-flow__node:has(.terminal-node)')
        .first()
        .getAttribute('data-id')
      expect(bossNodeId).toBeTruthy()

      await chooseVoiceBoss(window, bossNodeId as string)
      const indicator = window.getByTestId('voice-indicator')
      const holdButton = window.getByTestId('voice-hold-button')
      await expect(holdButton).toBeVisible()
      const readPhases = await recordVoicePhases(window)

      // A tap shorter than the minimum hold is cancelled and sends nothing.
      await holdPushToTalk(window, 50)
      await expect(indicator).toHaveAttribute('data-voice-phase', 'cancelled')

      const spoken = window.waitForRequest(request => request.url().endsWith('/voice/speak'))
      await holdPushToTalk(window, 600)
      await expect(agentNode)
        .toContainText(`[opencove-test-voice] heard: ${TRANSCRIPT}`)
        .catch(async (error: unknown) => {
          throw new Error(`Voice phases: ${JSON.stringify(await readPhases())}`, { cause: error })
        })
      await expect(agentNode).toContainText('[opencove-test-voice] instruction: true')
      await expect(agentNode).toContainText('[opencove-test-voice] replied')
      expect((await spoken).postDataJSON()).toMatchObject({ text: VOICE_SAY_LINE })
      await expect(indicator).toHaveCount(0, { timeout: 30_000 })

      // The spoken reply announces the finish, so the boss raises no standby banner.
      await expect(window.locator('[data-testid^="app-notification-"]')).toHaveCount(0)

      // The same turn by holding the on-screen button, as on a phone.
      const spokenAgain = window.waitForRequest(request => request.url().endsWith('/voice/speak'))
      const box = await holdButton.boundingBox()
      expect(box).toBeTruthy()
      await window.mouse.move(box!.x + box!.width / 2, box!.y + box!.height / 2)
      await window.mouse.down()
      await expect(holdButton).toHaveAttribute('data-voice-phase', 'listening')
      await window.waitForTimeout(600)
      await window.mouse.up()
      expect((await spokenAgain).postDataJSON()).toMatchObject({ text: VOICE_SAY_LINE })
      await expect(indicator).toHaveCount(0, { timeout: 30_000 })
    } finally {
      await electronApp.close()
    }
  })
})
